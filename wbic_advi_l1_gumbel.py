def _graph_to_adjmat(G):
    return np.array(G.get_adjacency().data, dtype=np.float64)

def simulate_er_dag_igraph(d: int, p_edge: float, rng=None):
    """
    用 igraph 生成 ER 无向图，再随机赋予一个拓扑顺序，定向成 DAG。
    约定: S[i,j]=1 表示 i -> j
    """
    if rng is None:
        rng = np.random.default_rng()

    p_edge = float(np.clip(p_edge, 0.0, 1.0))
    G_und = ig.Graph.Erdos_Renyi(n=d, p=p_edge, directed=False, loops=False)
    A_und = _graph_to_adjmat(G_und)

    perm = rng.permutation(d)
    pos = np.empty(d, dtype=int)
    pos[perm] = np.arange(d)

    S = np.zeros((d, d), dtype=np.float64)
    for i in range(d):
        for j in range(i + 1, d):
            if A_und[i, j] != 0:
                if pos[i] < pos[j]:
                    S[i, j] = 1.0
                else:
                    S[j, i] = 1.0
    return S

def simulate_er_bidirected_igraph(d: int, p_edge: float, rng=None):
    """
    用 igraph 生成无向 ER 图作为 bidirected 结构。
    返回对称 0/1 矩阵 C，且对角线为 1。
    """
    if rng is None:
        rng = np.random.default_rng()

    p_edge = float(np.clip(p_edge, 0.0, 1.0))
    G = ig.Graph.Erdos_Renyi(n=d, p=p_edge, directed=False, loops=False)
    A = _graph_to_adjmat(G)

    C = ((A + A.T) > 0).astype(np.float64)
    np.fill_diagonal(C, 1.0)
    return C

def sample_weighted_B_from_S(
    S,
    rng=None,
    abs_low=0.3,
    abs_high=1.5,
    allow_negative=True,
):
    """
    根据 0/1 结构矩阵 S 生成 weighted B_true.
    约定: B[i,j] 表示 i -> j
    """
    if rng is None:
        rng = np.random.default_rng()

    d = S.shape[0]
    B = np.zeros((d, d), dtype=np.float64)

    rows, cols = np.where(S != 0)
    for i, j in zip(rows, cols):
        mag = rng.uniform(abs_low, abs_high)
        sign = rng.choice([-1.0, 1.0]) if allow_negative else 1.0
        B[i, j] = sign * mag

    return B

def sample_weighted_Omega_from_C(
    C,
    rng=None,
    diag_low=1.0,
    diag_high=2.0,
    off_abs_low=0.1,
    off_abs_high=0.6,
    allow_negative=True,
    spd_floor=1e-3,
):
    """
    根据 0/1 结构矩阵 C 生成 weighted Omega_true.
    - 对角线随机正值
    - C[i,j]=1 的非对角位置给随机权重
    - 最后通过最小特征值修正保证正定:
          Omega <- Omega + soft_shift * I
      这里直接用线性 shift:
          shift = max(0, spd_floor - lambda_min)
    """
    if rng is None:
        rng = np.random.default_rng()

    d = C.shape[0]
    Omega = np.zeros((d, d), dtype=np.float64)

    diag_vals = rng.uniform(diag_low, diag_high, size=d)
    np.fill_diagonal(Omega, diag_vals)

    for i in range(d):
        for j in range(i + 1, d):
            if C[i, j] != 0:
                mag = rng.uniform(off_abs_low, off_abs_high)
                sign = rng.choice([-1.0, 1.0]) if allow_negative else 1.0
                val = sign * mag
                Omega[i, j] = val
                Omega[j, i] = val

    eigvals = np.linalg.eigvalsh(Omega)
    lam_min = eigvals.min()
    shift = max(0.0, spd_floor - lam_min)
    if shift > 0:
        Omega = Omega + shift * np.eye(d, dtype=np.float64)

    return Omega

def generate_random_ground_truth_er(
    d,
    p_dir,
    p_bidir,
    seed=None,
    B_abs_low=0.3,
    B_abs_high=1.5,
    Omega_diag_low=1.0,
    Omega_diag_high=2.0,
    Omega_off_abs_low=0.1,
    Omega_off_abs_high=0.6,
    B_allow_negative=True,
    Omega_allow_negative=True,
    spd_floor=1e-3,
):
    """
    一次性生成:
      - S_true: ER DAG 结构
      - C_true: ER bidirected 结构
      - B_true: 根据 S_true 加权
      - Omega_true: 根据 C_true 加权并修正为 SPD
    """
    rng = np.random.default_rng(seed)

    S_true = simulate_er_dag_igraph(d=d, p_edge=p_dir, rng=rng)
    C_true = simulate_er_bidirected_igraph(d=d, p_edge=p_bidir, rng=rng)

    B_true = sample_weighted_B_from_S(
        S_true,
        rng=rng,
        abs_low=B_abs_low,
        abs_high=B_abs_high,
        allow_negative=B_allow_negative,
    )

    Omega_true = sample_weighted_Omega_from_C(
        C_true,
        rng=rng,
        diag_low=Omega_diag_low,
        diag_high=Omega_diag_high,
        off_abs_low=Omega_off_abs_low,
        off_abs_high=Omega_off_abs_high,
        allow_negative=Omega_allow_negative,
        spd_floor=spd_floor,
    )

    return {
        "d": d,
        "S_true": S_true,
        "C_true": C_true,
        "B_true": B_true,
        "Omega_true": Omega_true,
    }


