class ContinuousADMGSearchOriginalParam(nn.Module):
    """
    Original-style parameterization:

      B_eff[i,j] = S[i,j] * zeta_B[i,j],  i < j

      L_ii = exp(zeta_D[i])
      L_ij = C[i,j] * zeta_L[i,j],        i > j
      Omega = L L^T

    Structure:
      S[i,j] = sigmoid(A_logits[i,j]) for i < j
      C[i,j] = sigmoid(U_logits[i,j]) for i < j, symmetric

    Convention:
      S[i,j], B[i,j] means i -> j.
    """

    def __init__(
        self,
        d,
        eps_sigma=1e-6,
        sigma_B_prior=2.0,
        dtype=torch.float64,
        device="cpu",
    ):
        super().__init__()

        self.d = d
        self.eps_sigma = eps_sigma
        self.sigma_B_prior = sigma_B_prior
        self.dtype = dtype
        self.device = device

        dir_mask = torch.ones(d, d, dtype=dtype, device=device) - torch.eye(d, dtype=dtype, device=device)
        c_upper_mask = torch.triu(torch.ones(d, d, dtype=dtype, device=device), diagonal=1)
        l_lower_mask = torch.tril(torch.ones(d, d, dtype=dtype, device=device), diagonal=-1)

        self.register_buffer("dir_mask", dir_mask)
        self.register_buffer("c_upper_mask", c_upper_mask)
        self.register_buffer("l_lower_mask", l_lower_mask)
        self.register_buffer("I", torch.eye(d, dtype=dtype, device=device))

        self.mu_B = nn.Parameter(torch.zeros(d, d, dtype=dtype, device=device))
        self.rho_B = nn.Parameter(torch.full((d, d), math.log(0.1), dtype=dtype, device=device))

        self.mu_L = nn.Parameter(torch.zeros(d, d, dtype=dtype, device=device))
        self.rho_L = nn.Parameter(torch.full((d, d), math.log(0.1), dtype=dtype, device=device))

        self.mu_D = nn.Parameter(torch.zeros(d, dtype=dtype, device=device))
        self.rho_D = nn.Parameter(torch.full((d,), math.log(0.1), dtype=dtype, device=device))

        self.A_logits = nn.Parameter(torch.zeros(d, d, dtype=dtype, device=device))
        self.U_logits = nn.Parameter(torch.zeros(d, d, dtype=dtype, device=device))

    def init_structure_logits(
        self,
        a_mean=0.0,
        a_std=0.1,
        u_mean=0.0,
        u_std=0.1,
        seed=None,
    ):
        if seed is not None:
            torch.manual_seed(seed)

        with torch.no_grad():
            self.A_logits.copy_(a_mean + a_std * torch.randn_like(self.A_logits))
            self.U_logits.copy_(u_mean + u_std * torch.randn_like(self.U_logits))

            self.A_logits.mul_(self.dir_mask)
            self.U_logits.mul_(self.c_upper_mask)

    def init_variational(self, seed=None):
        if seed is not None:
            torch.manual_seed(seed)

        with torch.no_grad():
            self.mu_B.copy_(0.01 * torch.randn_like(self.mu_B))
            self.mu_L.copy_(0.01 * torch.randn_like(self.mu_L))
            self.mu_D.copy_(0.01 * torch.randn_like(self.mu_D))

            self.rho_B.fill_(math.log(0.1))
            self.rho_L.fill_(math.log(0.1))
            self.rho_D.fill_(math.log(0.1))

            self.mu_B.mul_(self.dir_mask)
            self.mu_L.mul_(self.l_lower_mask)

    def sigma_from_rho(self, rho):
        return torch.exp(rho) + self.eps_sigma

    def soft_S(self):
        return torch.sigmoid(self.A_logits) * self.dir_mask

    def soft_C_upper(self):
        return torch.sigmoid(self.U_logits) * self.c_upper_mask

    def soft_C_full(self):
        Cup = self.soft_C_upper()
        return Cup + Cup.T + self.I

    def soft_C_lower(self):
        Cup = self.soft_C_upper()
        return Cup.T * self.l_lower_mask

    def sample_zeta(self, n_mc):
        sig_B = self.sigma_from_rho(self.rho_B)
        sig_L = self.sigma_from_rho(self.rho_L)
        sig_D = self.sigma_from_rho(self.rho_D)

        eps_B = torch.randn((n_mc, self.d, self.d), dtype=self.dtype, device=self.device)
        eps_L = torch.randn((n_mc, self.d, self.d), dtype=self.dtype, device=self.device)
        eps_D = torch.randn((n_mc, self.d), dtype=self.dtype, device=self.device)

        zeta_B = self.mu_B.unsqueeze(0) + sig_B.unsqueeze(0) * eps_B
        zeta_L = self.mu_L.unsqueeze(0) + sig_L.unsqueeze(0) * eps_L
        zeta_D = self.mu_D.unsqueeze(0) + sig_D.unsqueeze(0) * eps_D

        zeta_B = zeta_B * self.dir_mask
        zeta_L = zeta_L * self.l_lower_mask

        return zeta_B, zeta_L, zeta_D

    def build_B(self, zeta_B):
        """
        B_eff[i,j] = S[i,j] * zeta_B[i,j], i < j.
        """
        S = self.soft_S().unsqueeze(0)
        B = S * zeta_B
        return B

    def build_Omega_and_log_jac(self, zeta_L, zeta_D):
        """
        L_ii = exp(zeta_D_i)
        L_ij = C_ij * zeta_L_ij, i > j
        Omega = L L^T

        log_jac from diagonal exp transform:
          sum_i zeta_D_i
        """
        n_mc = zeta_D.shape[0]

        C_lower = self.soft_C_lower().unsqueeze(0)

        L = torch.zeros((n_mc, self.d, self.d), dtype=self.dtype, device=self.device)
        L = L + C_lower * zeta_L

        diag_vals = torch.exp(zeta_D)
        L = L + torch.diag_embed(diag_vals)

        Omega = L @ L.transpose(-1, -2)
        log_jac = zeta_D.sum(dim=1)

        return Omega, log_jac

    def log_likelihood(self, X, B, Omega):
        """
        X: [n,d]
        B: [mc,d,d], B[i,j] means i -> j
        Omega: [mc,d,d]

        X = E (I - B)^(-1)
        E = X (I - B)
        loglik = n log|det(I-B)| - 1/2 n log|Omega|
                 - 1/2 tr(E Omega^{-1} E^T)
                 - nd/2 log(2pi)

        For strictly upper-triangular B, log|det(I-B)| = 0,
        but computed explicitly for consistency.
        """
        n, p = X.shape
        mc = B.shape[0]

        ImB = self.I.unsqueeze(0) - B

        sign_imb, logdet_imb = torch.linalg.slogdet(ImB)
        sign_om, logdet_om = torch.linalg.slogdet(Omega)

        R = torch.matmul(X.unsqueeze(0), ImB)

        Omega_inv = torch.linalg.inv(Omega)
        quad = torch.einsum("mni,mij,mnj->m", R, Omega_inv, R)

        const = -0.5 * n * p * math.log(2.0 * math.pi)
        ll = n * logdet_imb - 0.5 * n * logdet_om - 0.5 * quad + const

        invalid = (sign_imb <= 0) | (sign_om <= 0) | (~torch.isfinite(ll))
        ll = torch.where(invalid, torch.full_like(ll, -1.0e30), ll)

        return ll

    def kl_terms(self):
        """
        Analytic KL:
          B prior: N(0, sigma_B_prior^2)
          L offdiag and D prior: N(0, 1)

        rho parameterization:
          sigma = exp(rho)
        """
        sig_B = self.sigma_from_rho(self.rho_B)
        sig_L = self.sigma_from_rho(self.rho_L)
        sig_D = self.sigma_from_rho(self.rho_D)

        sB2 = self.sigma_B_prior ** 2

        kl_B_mat = 0.5 * (
            sig_B**2 / sB2
            + self.mu_B**2 / sB2
            - 1.0
            - 2.0 * torch.log(sig_B)
            + math.log(sB2)
        )
        kl_B = (kl_B_mat * self.dir_mask).sum()

        kl_L_mat = 0.5 * (
            sig_L**2
            + self.mu_L**2
            - 1.0
            - 2.0 * torch.log(sig_L)
        )
        kl_L = (kl_L_mat * self.l_lower_mask).sum()

        kl_D_vec = 0.5 * (
            sig_D**2
            + self.mu_D**2
            - 1.0
            - 2.0 * torch.log(sig_D)
        )
        kl_D = kl_D_vec.sum()

        kl_Om = kl_L + kl_D
        kl_total = kl_B + kl_Om

        return kl_total, kl_B, kl_Om, kl_L, kl_D

    def objective(
        self,
        X,
        beta,
        n_mc=8,
        alpha_B=0.05,
        alpha_C=0.05,
        lambda_acyc = 1,
        include_log_jac=True,
    ):
        zeta_B, zeta_L, zeta_D = self.sample_zeta(n_mc=n_mc)

        B = self.build_B(zeta_B)
        Omega, log_jac = self.build_Omega_and_log_jac(zeta_L, zeta_D)

        ll = self.log_likelihood(X, B, Omega)

        if include_log_jac:
            mc_term = beta * ll + log_jac
        else:
            mc_term = beta * ll

        mc_mean = mc_term.mean()

        kl, kl_B, kl_Om, kl_L, kl_D = self.kl_terms()

        S_soft = self.soft_S()
        C_upper = self.soft_C_upper()

        l1_B = S_soft.sum()
        l1_C = C_upper.sum()
        h_acyc = torch.trace(torch.matrix_exp(S_soft * S_soft)) - self.d

        elbo = mc_mean - kl
        objective = elbo - alpha_B * l1_B - alpha_C * l1_C - lambda_acyc*h_acyc

        return {
            "objective": objective,
            "elbo": elbo,
            "mc_mean": mc_mean,
            "beta_ll_mean": (beta * ll).mean(),
            "ll_mean": ll.mean(),
            "log_jac_mean": log_jac.mean(),
            "kl": kl,
            "kl_B": kl_B,
            "kl_Om": kl_Om,
            "kl_L": kl_L,
            "kl_D": kl_D,
            "l1_B": l1_B,
            "l1_C": l1_C,
        }

    @torch.no_grad()
    def current_soft_graphs(self):
        S = self.soft_S().detach().cpu()
        C = self.soft_C_full().detach().cpu()
        return S, C

    @torch.no_grad()
    def threshold_graphs(self, tau_B=0.1, tau_C=0.1):
        S_soft = self.soft_S()
        C_up = self.soft_C_upper()
        S_bar = max(S_soft.mean(), tau_B)
        C_bar = max(torch.mean(C_up + C_up.T) / 2, tau_C)

        S_hat = (S_soft > S_bar).to(torch.float64)
        C_hat = (C_up > C_bar).to(torch.float64)
        C_hat = C_hat + C_hat.T + torch.eye(self.d, dtype=torch.float64, device=C_hat.device)

        return S_hat.detach().cpu(), C_hat.detach().cpu()


