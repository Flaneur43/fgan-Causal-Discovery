def run_multi_init_experiment_gumbel(
    gt,
    n_samples=1000,
    n_steps=3000,
    lr=1e-2,
    n_mc=8,
    sigma_B_prior=2.0,
    tau_gumbel=1.0,
    hard=False,
    tau_B=0.1,
    tau_C=0.1,
    init_configs=None,
    seed_data=42,
    device="cpu",
    include_log_jac=True,
    verbose = True
):
    S_true = gt["S_true"]
    C_true = gt["C_true"]
    B_true = gt["B_true"]
    Omega_true = gt["Omega_true"]

    X_np = simulate_linear_scm_i_to_j(
        n=n_samples,
        B=B_true,
        Omega=Omega_true,
        seed=seed_data,
    )

    if init_configs is None:
        init_configs = [
            {"name": "sparse_sparse", "a_mean": -3.0, "u_mean": -3.0, "std": 0.1, "seed": 101},
            {"name": "sparse_mid",    "a_mean": -3.0, "u_mean":  0.0, "std": 0.1, "seed": 102},
            {"name": "mid_mid",       "a_mean":  0.0, "u_mean":  0.0, "std": 0.1, "seed": 103},
            {"name": "dense_mid",     "a_mean":  3.0, "u_mean":  0.0, "std": 0.1, "seed": 104},
            {"name": "dense_dense",   "a_mean":  3.0, "u_mean":  3.0, "std": 0.1, "seed": 105},
        ]

    all_results = []

    S_true_t = torch.tensor(S_true, dtype=torch.float64)
    C_true_t = torch.tensor(C_true, dtype=torch.float64)

    for cfg in init_configs:
        print("\n" + "=" * 80)
        print(f"INIT: {cfg['name']}")
        print("=" * 80)

        res = fit_continuous_search_gumbel(
            X_np=X_np,
            n_steps=n_steps,
            lr=lr,
            n_mc=n_mc,
            sigma_B_prior=sigma_B_prior,
            tau_gumbel=tau_gumbel,
            hard=hard,
            init_a_mean=cfg["a_mean"],
            init_u_mean=cfg["u_mean"],
            init_std=cfg["std"],
            tau_B=tau_B,
            tau_C=tau_C,
            seed=cfg["seed"],
            device=device,
            verbose=verbose,
            include_log_jac=include_log_jac,
        )

        S_hat_t = torch.tensor(res["S_hat"], dtype=torch.float64)
        C_hat_t = torch.tensor(res["C_hat"], dtype=torch.float64)
        d = S_true_t.shape[0]
        pag_true = admg_to_pag(d,B_mat=S_true,Sigma_mat=C_true)
        try:
          # 尝试生成 PAG，如果 S_hat 包含环，这里会触发 NetworkXError
          pag_hat = admg_to_pag(d, B_mat=res["S_hat"], Sigma_mat=res["C_hat"])
          shd_res = compute_pag_metrics(pag_true, pag_hat)
          shd = shd_res["shd"]

          all_results.append({
            "init_name": cfg["name"],
            "config": cfg,
            "result": res,
            "shd": shd,
          })
          if verbose:
            print("\nFinal metrics:")
            print(
                {
                    "objective": res["final_objective"],
                    "elbo": res["final_elbo"],
                    "ll_mean": res["final_ll_mean"],
                    "kl": res["final_kl"],
                    "l1_B": res["final_l1_B"],
                    "l1_C": res["final_l1_C"],
                }
                )
            print("\nPag True:")
            print(pag_true)
            print("\nPag Hat:")
            print(pag_hat)
            print("\nSHD:")
            print(shd)
        except Exception as e:
          # 捕获错误并跳过该次初始化结果，继续下一次实验
          print(f"[Warning] Skipping init {cfg['name']} due to non-acyclic graph: {e}")
          continue

    all_results = sorted(
        all_results,
        key=lambda z: z["result"]["final_objective"],
        reverse=True,
    )

    if verbose:
        print("\n" + "=" * 80)
        print("SUMMARY OVER INITIALIZATIONS")
        print("=" * 80)

        for k, rr in enumerate(all_results, 1):
            print(
                f"{k:2d}. {rr['init_name']:<15s} "
                f"obj={rr['result']['final_objective']:12.4f} "
                f"elbo={rr['result']['final_elbo']:12.4f} "
                f"ll={rr['result']['final_ll_mean']:12.4f} "
                f"kl={rr['result']['final_kl']:10.4f} "
                f"l1B={rr['result']['final_l1_B']:8.4f} "
                f"l1C={rr['result']['final_l1_C']:8.4f} "
                f"SHD={rr['shd']}"
            )

    return {
        "ground_truth": gt,
        "X": X_np,
        "all_results": all_results,
    }

