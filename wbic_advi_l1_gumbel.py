# 4. Continuous ADMG search with Gumbel-Sigmoid gates
# ============================================================

class ContinuousADMGSearchGumbel(nn.Module):
    """
    Original parameterization for model parameters:
      B_eff[i,j] = S[i,j] * zeta_B[i,j],  i < j
      L_ii = exp(zeta_D[i])
      L_ij = C_lower[i,j] * zeta_L[i,j], i > j
      Omega = L L^T

    Structure gates:
      S and C are generated by Binary Concrete / Gumbel-Sigmoid from logits A, U
      No L1 penalty
    """

    def __init__(
        self,
        d,
        eps_sigma=1e-6,
        sigma_B_prior=2.0,
        tau_gumbel=1.0,
        hard=False,
        dtype=torch.float64,
        device="cpu",
    ):
        super().__init__()

        self.d = d
        self.eps_sigma = eps_sigma
        self.sigma_B_prior = sigma_B_prior
        self.tau_gumbel = tau_gumbel
        self.hard = hard
        self.dtype = dtype
        self.device = device

        dir_mask = torch.ones(d, d, dtype=dtype, device=device) - torch.eye(d, dtype=dtype, device=device)
        c_upper_mask = torch.triu(torch.ones(d, d, dtype=dtype, device=device), diagonal=1)
        l_lower_mask = torch.tril(torch.ones(d, d, dtype=dtype, device=device), diagonal=-1)

        self.register_buffer("dir_mask", dir_mask)
        self.register_buffer("c_upper_mask", c_upper_mask)
        self.register_buffer("l_lower_mask", l_lower_mask)
        self.register_buffer("I", torch.eye(d, dtype=dtype, device=device))

        # variational params
        self.mu_B = nn.Parameter(torch.zeros(d, d, dtype=dtype, device=device))
        self.rho_B = nn.Parameter(torch.full((d, d), math.log(0.1), dtype=dtype, device=device))

        self.mu_L = nn.Parameter(torch.zeros(d, d, dtype=dtype, device=device))
        self.rho_L = nn.Parameter(torch.full((d, d), math.log(0.1), dtype=dtype, device=device))

        self.mu_D = nn.Parameter(torch.zeros(d, dtype=dtype, device=device))
        self.rho_D = nn.Parameter(torch.full((d,), math.log(0.1), dtype=dtype, device=device))

        # structure logits
        self.A_logits = nn.Parameter(torch.zeros(d, d, dtype=dtype, device=device))
        self.U_logits = nn.Parameter(torch.zeros(d, d, dtype=dtype, device=device))

    # --------------------------------------------------------
    # init
    # --------------------------------------------------------
    def init_structure_logits(
        self,
        a_mean=0.0,
        a_std=0.1,
        u_mean=0.0,
        u_std=0.1,
        seed=None,
    ):
        if seed is not None:
            torch.manual_seed(seed)

        with torch.no_grad():
            self.A_logits.copy_(a_mean + a_std * torch.randn_like(self.A_logits))
            self.U_logits.copy_(u_mean + u_std * torch.randn_like(self.U_logits))
            self.A_logits.mul_(self.dir_mask)
            self.U_logits.mul_(self.c_upper_mask)

    def init_variational(self, seed=None):
        if seed is not None:
            torch.manual_seed(seed)

        with torch.no_grad():
            self.mu_B.copy_(0.01 * torch.randn_like(self.mu_B))
            self.mu_L.copy_(0.01 * torch.randn_like(self.mu_L))
            self.mu_D.copy_(0.01 * torch.randn_like(self.mu_D))

            self.rho_B.fill_(math.log(0.1))
            self.rho_L.fill_(math.log(0.1))
            self.rho_D.fill_(math.log(0.1))

            self.mu_B.mul_(self.dir_mask)
            self.mu_L.mul_(self.l_lower_mask)

    # --------------------------------------------------------
    # helpers
    # --------------------------------------------------------
    def sigma_from_rho(self, rho):
        return torch.exp(rho) + self.eps_sigma

    def _sample_binary_concrete(self, logits, tau=None, hard=None):
        """
        Binary Concrete / Gumbel-Sigmoid sample:
          y = sigmoid((logits + g) / tau),   g ~ Logistic(0,1)
        hard=True uses straight-through thresholding.
        """
        if tau is None:
            tau = self.tau_gumbel
        if hard is None:
            hard = self.hard

        u = torch.rand_like(logits)
        eps = 1e-20
        g = torch.log(u + eps) - torch.log(1.0 - u + eps)
        y_soft = torch.sigmoid((logits + g) / tau)

        if not hard:
            return y_soft

        y_hard = (y_soft > 0.5).to(y_soft.dtype)
        y = y_hard.detach() - y_soft.detach() + y_soft
        return y

    def sample_soft_S(self):
        return self._sample_binary_concrete(self.A_logits) * self.dir_mask

    def sample_soft_C_upper(self):
        return self._sample_binary_concrete(self.U_logits) * self.c_upper_mask

    def deterministic_S(self):
        return torch.sigmoid(self.A_logits) * self.dir_mask

    def deterministic_C_upper(self):
        return torch.sigmoid(self.U_logits) * self.c_upper_mask

    def deterministic_C_full(self):
        Cup = self.deterministic_C_upper()
        return Cup + Cup.T + self.I

    def sample_C_lower(self):
        Cup = self.sample_soft_C_upper()
        return Cup.T * self.l_lower_mask, Cup

    def sample_zeta(self, n_mc):
        sig_B = self.sigma_from_rho(self.rho_B)
        sig_L = self.sigma_from_rho(self.rho_L)
        sig_D = self.sigma_from_rho(self.rho_D)

        eps_B = torch.randn((n_mc, self.d, self.d), dtype=self.dtype, device=self.device)
        eps_L = torch.randn((n_mc, self.d, self.d), dtype=self.dtype, device=self.device)
        eps_D = torch.randn((n_mc, self.d), dtype=self.dtype, device=self.device)

        zeta_B = self.mu_B.unsqueeze(0) + sig_B.unsqueeze(0) * eps_B
        zeta_L = self.mu_L.unsqueeze(0) + sig_L.unsqueeze(0) * eps_L
        zeta_D = self.mu_D.unsqueeze(0) + sig_D.unsqueeze(0) * eps_D

        zeta_B = zeta_B * self.dir_mask
        zeta_L = zeta_L * self.l_lower_mask

        return zeta_B, zeta_L, zeta_D

    # --------------------------------------------------------
    # model build
    # --------------------------------------------------------
    def build_B(self, zeta_B, S_soft):
        """
        B_eff[i,j] = S_soft[i,j] * zeta_B[i,j], i < j
        """
        return zeta_B * S_soft.unsqueeze(0)

    def build_Omega_and_log_jac(self, zeta_L, zeta_D, C_lower_soft):
        """
        L_ii = exp(zeta_D_i)
        L_ij = C_lower_soft[i,j] * zeta_L[i,j], i > j
        Omega = L L^T
        log_jac = sum_i zeta_D_i
        """
        n_mc = zeta_D.shape[0]

        L = torch.zeros((n_mc, self.d, self.d), dtype=self.dtype, device=self.device)
        L = L + C_lower_soft.unsqueeze(0) * zeta_L
        diag_vals = torch.exp(zeta_D)
        L = L + torch.diag_embed(diag_vals)

        Omega = L @ L.transpose(-1, -2)
        log_jac = zeta_D.sum(dim=1)
        return Omega, log_jac

    def log_likelihood(self, X, B, Omega):
        n, p = X.shape
        ImB = self.I.unsqueeze(0) - B

        sign_imb, logdet_imb = torch.linalg.slogdet(ImB)
        sign_om, logdet_om = torch.linalg.slogdet(Omega)

        R = torch.matmul(X.unsqueeze(0), ImB)
        Omega_inv = torch.linalg.inv(Omega)
        quad = torch.einsum("mni,mij,mnj->m", R, Omega_inv, R)

        const = -0.5 * n * p * math.log(2.0 * math.pi)
        ll = n * logdet_imb - 0.5 * n * logdet_om - 0.5 * quad + const

        invalid = (sign_imb <= 0) | (sign_om <= 0) | (~torch.isfinite(ll))
        ll = torch.where(invalid, torch.full_like(ll, -1.0e30), ll)
        return ll

    def kl_terms(self):
        sig_B = self.sigma_from_rho(self.rho_B)
        sig_L = self.sigma_from_rho(self.rho_L)
        sig_D = self.sigma_from_rho(self.rho_D)

        sB2 = self.sigma_B_prior ** 2

        kl_B_mat = 0.5 * (
            sig_B**2 / sB2
            + self.mu_B**2 / sB2
            - 1.0
            - 2.0 * torch.log(sig_B)
            + math.log(sB2)
        )
        kl_B = (kl_B_mat * self.dir_mask).sum()

        kl_L_mat = 0.5 * (
            sig_L**2
            + self.mu_L**2
            - 1.0
            - 2.0 * torch.log(sig_L)
        )
        kl_L = (kl_L_mat * self.l_lower_mask).sum()

        kl_D_vec = 0.5 * (
            sig_D**2
            + self.mu_D**2
            - 1.0
            - 2.0 * torch.log(sig_D)
        )
        kl_D = kl_D_vec.sum()

        kl_Om = kl_L + kl_D
        kl_total = kl_B + kl_Om
        return kl_total, kl_B, kl_Om, kl_L, kl_D

    # --------------------------------------------------------
    # objective
    # --------------------------------------------------------
    def objective(
        self,
        X,
        beta,
        n_mc=8,
        lambda_acyc = 0.5,
        include_log_jac=True,
    ):
        zeta_B, zeta_L, zeta_D = self.sample_zeta(n_mc=n_mc)

        # one gate sample per objective evaluation
        S_soft = self.sample_soft_S()
        C_lower_soft, C_upper_soft = self.sample_C_lower()

        B = self.build_B(zeta_B, S_soft)
        Omega, log_jac = self.build_Omega_and_log_jac(zeta_L, zeta_D, C_lower_soft)

        ll = self.log_likelihood(X, B, Omega)

        if include_log_jac:
            mc_term = beta * ll + log_jac
        else:
            mc_term = beta * ll

        mc_mean = mc_term.mean()

        kl, kl_B, kl_Om, kl_L, kl_D = self.kl_terms()
        h_acyc = torch.trace(torch.matrix_exp(S_soft * S_soft)) - self.d
        elbo = mc_mean - kl
        objective = elbo - lambda_acyc*h_acyc

        return {
            "objective": objective,
            "elbo": elbo,
            "mc_mean": mc_mean,
            "beta_ll_mean": (beta * ll).mean(),
            "ll_mean": ll.mean(),
            "log_jac_mean": log_jac.mean(),
            "kl": kl,
            "kl_B": kl_B,
            "kl_Om": kl_Om,
            "kl_L": kl_L,
            "kl_D": kl_D,
            "S_sample_mean": S_soft.sum(),
            "C_sample_mean": C_upper_soft.sum(),
        }

    # --------------------------------------------------------
    # outputs
    # --------------------------------------------------------
    @torch.no_grad()
    def current_soft_graphs(self):
        S = self.deterministic_S().detach().cpu()
        C = self.deterministic_C_full().detach().cpu()
        return S, C

    @torch.no_grad()
    def threshold_graphs(self, tau_B=0.1, tau_C=0.1):
        S_prob = self.deterministic_S()
        C_up_prob = self.deterministic_C_upper()
        S_bar = max(S_prob.mean(), tau_B)
        C_bar = max(torch.mean(C_up_prob + C_up_prob.T) / 2, tau_C)

        S_hat = (S_prob > S_bar).to(torch.float64)
        C_hat = (C_up_prob > C_bar).to(torch.float64)
        C_hat = C_hat + C_hat.T + torch.eye(self.d, dtype=torch.float64, device=C_hat.device)

        return S_hat.detach().cpu(), C_hat.detach().cpu()

# ============================================================
# 5. Single optimization run
# ============================================================

def fit_continuous_search_gumbel(
    X_np,
    n_steps=3000,
    lr=1e-2,
    n_mc=8,
    sigma_B_prior=2.0,
    tau_gumbel=1.0,
    hard=False,
    init_a_mean=0.0,
    init_u_mean=0.0,
    init_std=0.1,
    tau_B=0.1,
    tau_C=0.1,
    lambda_acyc_init=1.0,    # 初始权重
    lambda_acyc_final=100.0,  # 结束权重
    seed=123,
    device="cpu",
    verbose=True,
    include_log_jac=True,
    grad_clip=10.0,
):
    torch.manual_seed(seed)
    np.random.seed(seed)

    X = torch.tensor(X_np, dtype=torch.float64, device=device)
    n, d_local = X.shape
    beta = 1.0 / math.log(n)

    model = ContinuousADMGSearchGumbel(
        d=d_local,
        sigma_B_prior=sigma_B_prior,
        tau_gumbel=tau_gumbel,
        hard=hard,
        dtype=torch.float64,
        device=device,
    ).to(device=device, dtype=torch.float64)

    model.init_variational(seed=seed)
    model.init_structure_logits(
        a_mean=init_a_mean,
        a_std=init_std,
        u_mean=init_u_mean,
        u_std=init_std,
        seed=seed + 1,
    )

    optimizer = optim.Adam(model.parameters(), lr=lr)

    history = {
        "objective": [],
        "elbo": [],
        "mc_mean": [],
        "beta_ll_mean": [],
        "ll_mean": [],
        "log_jac_mean": [],
        "kl": [],
        "kl_B": [],
        "kl_Om": [],
        "kl_L": [],
        "kl_D": [],
        "S_sample_mean": [],
        "C_sample_mean": [],
    }

    for t in range(n_steps):
        # 指数增长计算当前步骤的权重
        curr_lambda = math.exp(math.log(lambda_acyc_init) + t * (math.log(lambda_acyc_final) - math.log(lambda_acyc_init)) / n_steps)
        optimizer.zero_grad()

        out = model.objective(
            X=X,
            beta=beta,
            n_mc=n_mc,
            lambda_acyc=curr_lambda,
            include_log_jac=include_log_jac,
        )

        loss = -out["objective"]
        loss.backward()

        if grad_clip is not None:
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=grad_clip)

        optimizer.step()

        for k in history:
            history[k].append(float(out[k].detach().cpu()))

        if verbose and (t == 0 or (t + 1) % 200 == 0):
            print(
                f"[step {t+1:5d}] "
                f"obj={history['objective'][-1]:12.4f} "
                f"elbo={history['elbo'][-1]:12.4f} "
                f"ll={history['ll_mean'][-1]:12.4f} "
                f"logJ={history['log_jac_mean'][-1]:9.4f} "
                f"kl={history['kl'][-1]:10.4f} "
                f"Ssum={history['S_sample_mean'][-1]:8.4f} "
                f"Csum={history['C_sample_mean'][-1]:8.4f}"
            )

    S_soft, C_soft = model.current_soft_graphs()
    S_hat, C_hat = model.threshold_graphs(tau_B=tau_B, tau_C=tau_C)

    result = {
        "model": model,
        "history": history,
        "S_soft": S_soft.numpy(),
        "C_soft": C_soft.numpy(),
        "S_hat": S_hat.numpy(),
        "C_hat": C_hat.numpy(),
        "final_objective": history["objective"][-1],
        "final_elbo": history["elbo"][-1],
        "final_ll_mean": history["ll_mean"][-1],
        "final_kl": history["kl"][-1],
    }

    return result

