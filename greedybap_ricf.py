def admg_to_pag(p, edges=None, biedges=None, B_mat=None, Sigma_mat=None):
    """
    将 ADMG 转换为 PAG
    参数:
    - p: 观测变量的数量 (int)
    - edges: 有向边列表, 如 [(0, 2)]
    - biedges: 双向边列表, 如 [(0, 1), (1, 2)]
    - B_mat: 有向边权重矩阵 (可选)
    - Sigma_mat: 噪声协方差矩阵 (可选)
    """

    # 1. 初始化观测变量节点
    nodes = [GraphNode(str(i)) for i in range(p)]
    all_nodes = list(nodes)
    latent_nodes = []

    # 2. 创建一个空的 DAG 对象
    # 注意：dag2pag 需要输入一个包含显变量和隐变量的完整 DAG
    dag = Dag(all_nodes)

    # 3. 处理有向边 (Directed Edges)
    if B_mat is not None:
        # 从矩阵提取有向边 (B_ij 表示 i -> j)
        for i in range(p):
            for j in range(p):
                if B_mat[i, j] != 0:
                    dag.add_directed_edge(nodes[i], nodes[j])
    elif edges is not None:
        for i, j in edges:
            dag.add_directed_edge(nodes[i], nodes[j])

    # 4. 处理双向边 (Bidirected Edges) -> 转换为隐变量结构
    # 每条双向边 i <-> j 变成 L -> i 和 L -> j
    if Sigma_mat is not None:
        # 从矩阵提取双向边 (只看上三角，排除对角线)
        for i in range(p):
            for j in range(i + 1, p):
                if Sigma_mat[i, j] != 0:
                    # 创建新的隐变量节点
                    l_node = GraphNode(f"L_{i}_{j}")
                    dag.add_node(l_node)
                    latent_nodes.append(l_node)
                    # 添加从隐变量到两个观测点的有向边
                    dag.add_directed_edge(l_node, nodes[i])
                    dag.add_directed_edge(l_node, nodes[j])
    elif biedges is not None:
        for i, j in biedges:
            l_node = GraphNode(f"L_{i}_{j}")
            dag.add_node(l_node)
            latent_nodes.append(l_node)
            dag.add_directed_edge(l_node, nodes[i])
            dag.add_directed_edge(l_node, nodes[j])

    # 5. 调用 causal-learn 函数将 DAG 转为 PAG
    # 第二个参数是需要 marginalize 掉的隐变量列表
    pag = dag2pag(dag, latent_nodes)

    return pag

def compute_pag_metrics(true_pag, est_pag):
    """
    计算 SHD, Skeleton F1, Arrowhead F1
    基于 causal-learn 的 GeneralGraph 对象
    """
    # 获取邻接矩阵 (graph property stores the matrix)
    # causal-learn 矩阵定义: M[i, j] 表示 i 和 j 之间在 j 端点的类型
    # 0: No Edge, 1: Circle, 2: Arrow, 3: Tail

    true_adj = true_pag.graph
    est_adj = est_pag.graph
    p = true_adj.shape[0]

    # --- 1. Skeleton F1 ---
    # 只需要看是否有边 (非0)，只遍历上三角避免重复
    tp_skel = 0
    fp_skel = 0
    fn_skel = 0

    for i in range(p):
        for j in range(i + 1, p):
            has_edge_true = (true_adj[i, j] != 0)
            has_edge_est = (est_adj[i, j] != 0)

            if has_edge_true and has_edge_est:
                tp_skel += 1
            elif not has_edge_true and has_edge_est:
                fp_skel += 1
            elif has_edge_true and not has_edge_est:
                fn_skel += 1

    precision_skel = tp_skel / (tp_skel + fp_skel) if (tp_skel + fp_skel) > 0 else 0
    recall_skel = tp_skel / (tp_skel + fn_skel) if (tp_skel + fn_skel) > 0 else 0
    f1_skel = 2 * precision_skel * recall_skel / (precision_skel + recall_skel) if (precision_skel + recall_skel) > 0 else 0

    # --- 2. Arrowhead F1 ---
    # 统计所有箭头 (Arrow = 2) 的预测情况
    # 遍历整个矩阵 (包括 i,j 和 j,i)，因为箭头是有方向的
    tp_arrow = 0
    fp_arrow = 0
    fn_arrow = 0

    # ARROW 在 causal-learn Endpoint 中通常对应值 2
    ARROW_MARK = Endpoint.ARROW.value

    for i in range(p):
        for j in range(p):
            if i == j: continue

            # True PAG 在 j 处是否有箭头
            is_arrow_true = (true_adj[i, j] == ARROW_MARK)
            # Est PAG 在 j 处是否有箭头
            is_arrow_est = (est_adj[i, j] == ARROW_MARK)

            if is_arrow_true and is_arrow_est:
                tp_arrow += 1
            elif not is_arrow_true and is_arrow_est:
                fp_arrow += 1
            elif is_arrow_true and not is_arrow_est:
                fn_arrow += 1

    precision_arrow = tp_arrow / (tp_arrow + fp_arrow) if (tp_arrow + fp_arrow) > 0 else 0
    recall_arrow = tp_arrow / (tp_arrow + fn_arrow) if (tp_arrow + fn_arrow) > 0 else 0
    f1_arrow = 2 * precision_arrow * recall_arrow / (precision_arrow + recall_arrow) if (precision_arrow + recall_arrow) > 0 else 0

    # --- 3. SHD (Structural Hamming Distance) ---
    # 定义：增加/删除边 + 修改端点方向的操作总数
    # 策略：
    # - 边存在性不同: SHD + 1

    shd = 0
    for i in range(p):
        for j in range(i + 1, p):
            diff = (true_adj[i,j]!=est_adj[i,j]) or (true_adj[j,i]!=est_adj[j,i])
            if diff:
                shd += 1.0

    return {
        "shd": int(shd) if shd.is_integer() else shd,
        "f1_skeleton": round(f1_skel, 4),
        "f1_arrowhead": round(f1_arrow, 4),
        "precision_arrow": round(precision_arrow, 4),
        "recall_arrow": round(recall_arrow, 4)
    }

