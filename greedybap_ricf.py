def graph_to_string(G: BAPGraph) -> str:
    d = G.d
    directed = []
    bidirected = []
    for i in range(d):
        for j in range(d):
            if G.D[i, j] == 1:
                directed.append(f"{i}->{j}")
    for i in range(d):
        for j in range(i + 1, d):
            if G.C[i, j] == 1:
                bidirected.append(f"{i}<->{j}")
    return (
        f"Directed: {directed}\n"
        f"Bidirected: {bidirected}\n"
        f"#dir={G.num_directed_edges()}, #bi={G.num_bidirected_edges()}, #total={G.num_edges()}"
    )

