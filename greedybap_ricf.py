# 3. Uniform random BAP generation via MCMC-style restart
#    (following the paper's idea)
# ============================================================

def random_bap_mcmc(
    d: int,
    burnin: int = 500,
    seed: Optional[int] = None,
    start_graph: Optional[BAPGraph] = None,
) -> BAPGraph:
    """
    Approximate uniform random restart graph using the paper's MCMC-style idea.
    """
    rng = random.Random(seed)

    if start_graph is None:
        G = empty_bap(d)
    else:
        G = start_graph.copy()

    for _ in range(burnin):
        i = rng.randrange(d)
        j = rng.randrange(d - 1)
        if j >= i:
            j += 1

        sigma = rng.random() < 0.5

        a, b = min(i, j), max(i, j)
        current_has_edge = has_any_edge(G, a, b)

        if current_has_edge:
            # if edge exists:
            #   sigma=0 => delete
            #   sigma=1 => keep
            if not sigma:
                G = set_edge_state(G, a, b, "none")
        else:
            # if no edge:
            #   sigma=0 => try add directed i -> j
            #   sigma=1 => add bidirected
            if not sigma:
                # note: use ordered pair (i,j)
                H = G.copy()
                if G.C[i, j] == 0 and G.C[j, i] == 0 and G.D[j, i] == 0 and G.D[i, j] == 0:
                    H.D[i, j] = 1
                    if is_acyclic(H.D):
                        G = H
            else:
                H = G.copy()
                if H.D[a, b] == 0 and H.D[b, a] == 0:
                    H.C[a, b] = 1
                    H.C[b, a] = 1
                    G = H

    G.validate()
    return G

