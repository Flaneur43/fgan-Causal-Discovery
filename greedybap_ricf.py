def is_acyclic(D: np.ndarray) -> bool:
    """
    Check acyclicity of directed adjacency matrix D using Kahn's algorithm.
    D[i,j]=1 means i -> j
    """
    d = D.shape[0]
    indeg = D.sum(axis=0).astype(int).tolist()
    queue = [i for i in range(d) if indeg[i] == 0]
    visited = 0

    # outgoing from i are D[i,:]
    while queue:
        v = queue.pop()
        visited += 1
        children = np.where(D[v] != 0)[0]
        for ch in children:
            indeg[ch] -= 1
            if indeg[ch] == 0:
                queue.append(ch)

    return visited == d

def can_add_directed_edge(D: np.ndarray, i: int, j: int) -> bool:
    """
    Whether adding i -> j keeps the directed part acyclic.
    """
    if i == j:
        return False
    if D[i, j] == 1:
        return False

    D_new = D.copy()
    D_new[i, j] = 1
    return is_acyclic(D_new)

def has_any_edge(G: BAPGraph, i: int, j: int) -> bool:
    """
    Whether the unordered pair {i,j} has any edge.
    """
    return (G.D[i, j] == 1) or (G.D[j, i] == 1) or (G.C[i, j] == 1)

def edge_state(G: BAPGraph, i: int, j: int) -> str:
    """
    For i < j:
      "none"
      "i->j"
      "j->i"
      "bi"
    """
    assert i < j
    if G.D[i, j] == 1:
        return "i->j"
    elif G.D[j, i] == 1:
        return "j->i"
    elif G.C[i, j] == 1:
        return "bi"
    else:
        return "none"

def set_edge_state(G: BAPGraph, i: int, j: int, state: str) -> BAPGraph:
    """
    Return a new graph with the unordered pair {i,j} set to the given state.
    i < j
    """
    assert i < j
    H = G.copy()

    # clear current state on pair {i,j}
    H.D[i, j] = 0
    H.D[j, i] = 0
    H.C[i, j] = 0
    H.C[j, i] = 0

    if state == "none":
        pass
    elif state == "i->j":
        H.D[i, j] = 1
    elif state == "j->i":
        H.D[j, i] = 1
    elif state == "bi":
        H.C[i, j] = 1
        H.C[j, i] = 1
    else:
        raise ValueError(f"Unknown state: {state}")

    # validity checks
    if not np.all((H.D + H.D.T + H.C) <= 1):
        raise ValueError("Bow-free violated after edge assignment.")
    if not is_acyclic(H.D):
        raise ValueError("Directed cycle created.")

    return H

def all_local_neighbors(G: BAPGraph) -> List[BAPGraph]:
    """
    Local neighborhood used in greedy hill climbing.

    For each unordered pair {i,j}, possible states are:
      none, i->j, j->i, bi
    and we allow changing to any other valid state differing by one local edit.
    """
    d = G.d
    neighbors = []
    seen = set()

    for i in range(d):
        for j in range(i + 1, d):
            cur = edge_state(G, i, j)
            candidates = ["none", "i->j", "j->i", "bi"]

            for new_state in candidates:
                if new_state == cur:
                    continue
                try:
                    H = set_edge_state(G, i, j, new_state)
                    key = H.key()
                    if key not in seen:
                        seen.add(key)
                        neighbors.append(H)
                except ValueError:
                    pass

    return neighbors

