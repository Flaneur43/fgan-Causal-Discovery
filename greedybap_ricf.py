def run_one_experiment(
    exp_id,
    *,
    d,
    n,
    p_dir,
    p_bidir,
    gt_seed=None,
    data_seed=None,
    search_seed=None,
    gt_kwargs=None,
    search_kwargs=None,
    device="cpu",
    dtype=torch.float64,
):
    """
    单次实验流程：
      1) 生成 ground truth
      2) 根据 ground truth 参数生成数据
      3) 用 bap_greedy_search 估计图
      4) GT / estimate 转 PAG
      5) 计算 SHD 等指标
      6) 打印结果
    """
    if gt_kwargs is None:
        gt_kwargs = {}
    if search_kwargs is None:
        search_kwargs = {}

    # ---------------------------
    # (1) 生成 GT
    # ---------------------------
    gt = generate_random_ground_truth_er(
        d=d,
        p_dir=p_dir,
        p_bidir=p_bidir,
        seed=gt_seed,
        **gt_kwargs
    )

    S_true = np.asarray(gt["S_true"]).astype(int)
    C_true = np.asarray(gt["C_true"]).astype(int)
    B_true = np.asarray(gt["B_true"], dtype=np.float64)
    Omega_true = np.asarray(gt["Omega_true"], dtype=np.float64)

    # ---------------------------
    # (2) 生成数据
    # ---------------------------
    X, Sigma_x = simulate_linear_gaussian_bap_data(
        B_true=B_true,
        Omega_true=Omega_true,
        n=n,
        seed=data_seed,
        dtype=dtype,
    )
    X = X.to(device)

    # ---------------------------
    # (3) BAP 搜索估计
    # ---------------------------
    est_result = bap_greedy_search(
        X,
        seed=search_seed,
        dtype=dtype,
        device=device,
        **search_kwargs
    )

    est_graph = est_result["best_graph"]
    best_score = est_result["best_score"]

    S_est, C_est = graph_to_SC(est_graph)

    # ---------------------------
    # (4) GT / EST 转 PAG
    # 这里按你的函数签名来：
    # admg_to_pag(p, B_mat=None, Sigma_mat=None)
    #
    # 其中：
    #   B_mat   <- S (directed adjacency)
    #   Sigma_mat <- C (bidirected adjacency)
    # ---------------------------
    true_pag = admg_to_pag(p=d, B_mat=S_true, Sigma_mat=C_true)
    est_pag = admg_to_pag(p=d, B_mat=S_est, Sigma_mat=C_est)

    # ---------------------------
    # (5) PAG 指标
    # ---------------------------
    metrics = compute_pag_metrics(true_pag, est_pag)

    # ---------------------------
    # (6) 打印
    # ---------------------------
    print("\n" + "=" * 100)
    print(f"Experiment {exp_id}")
    print("-" * 100)

    print(format_matrix(S_true, "GT S_true"))
    print(format_matrix(C_true, "GT C_true"))
    print()

    print(format_matrix(S_est, "EST S_est"))
    print(format_matrix(C_est, "EST C_est"))
    print()

    print_pag_object(true_pag, name="GT PAG")
    print()
    print_pag_object(est_pag, name="EST PAG")
    print()

    print(f"Best search score = {best_score:.6f}")
    print(f"Metrics = {metrics}")
    print(f"SHD = {metrics['shd']}")

    return {
        "exp_id": exp_id,
        "gt": gt,
        "X": X.detach().cpu().numpy(),
        "Sigma_x": Sigma_x,
        "est_result": est_result,
        "S_true": S_true,
        "C_true": C_true,
        "S_est": S_est,
        "C_est": C_est,
        "true_pag": true_pag,
        "est_pag": est_pag,
        "metrics": metrics,
    }

# ============================================================
# 5. 多次实验并汇总平均 SHD
# ============================================================

def run_bap_pag_benchmark(
    *,
    n_experiments=10,
    d=5,
    n=500,
    p_dir=0.2,
    p_bidir=0.1,
    gt_seed_base=1000,
    data_seed_base=2000,
    search_seed_base=3000,
    gt_kwargs=None,
    search_kwargs=None,
    device="cpu",
    dtype=torch.float64,
):
    """
    多次实验：
      - 每次生成一个新的 GT
      - 生成数据
      - BAP 搜索
      - 转 PAG
      - 计算 SHD
      - 最后输出平均 SHD
    """
    if gt_kwargs is None:
        gt_kwargs = {}
    if search_kwargs is None:
        search_kwargs = {}

    all_results = []
    shd_list = []

    for t in range(n_experiments):
        result_t = run_one_experiment(
            exp_id=t + 1,
            d=d,
            n=n,
            p_dir=p_dir,
            p_bidir=p_bidir,
            gt_seed=gt_seed_base + t if gt_seed_base is not None else None,
            data_seed=data_seed_base + t if data_seed_base is not None else None,
            search_seed=search_seed_base + t if search_seed_base is not None else None,
            gt_kwargs=gt_kwargs,
            search_kwargs=search_kwargs,
            device=device,
            dtype=dtype,
        )

        all_results.append(result_t)
        shd_list.append(float(result_t["metrics"]["shd"]))

    mean_shd = float(np.mean(shd_list)) if len(shd_list) > 0 else float("nan")
    std_shd = float(np.std(shd_list)) if len(shd_list) > 0 else float("nan")

    print("\n" + "#" * 100)
    print("Summary over all experiments")
    print("#" * 100)
    print(f"Number of experiments = {n_experiments}")
    print(f"SHD list = {shd_list}")
    print(f"Average SHD = {mean_shd:.6f}")
    print(f"Std SHD = {std_shd:.6f}")

    return {
        "all_results": all_results,
        "shd_list": shd_list,
        "mean_shd": mean_shd,
        "std_shd": std_shd,
    }

