def center_data_np(X):
    """
    Center data column-wise.
    """
    X = np.asarray(X, dtype=np.float64)
    return X - X.mean(axis=0, keepdims=True)

def safe_slogdet(A, jitter=1e-10, max_tries=8):
    """
    Stable slogdet with diagonal jitter if needed.
    """
    A = np.asarray(A, dtype=np.float64)
    d = A.shape[0]

    for k in range(max_tries):
        Aj = A + (jitter * (10 ** k)) * np.eye(d)
        sign, logdet = np.linalg.slogdet(Aj)
        if sign > 0 and np.isfinite(logdet):
            return sign, logdet, Aj

    sign, logdet = np.linalg.slogdet(A)
    return sign, logdet, A

def safe_inverse_spd(A, jitter=1e-10, max_tries=8):
    """
    Invert SPD-like matrix with jitter.
    """
    A = np.asarray(A, dtype=np.float64)
    d = A.shape[0]

    for k in range(max_tries):
        Aj = A + (jitter * (10 ** k)) * np.eye(d)
        try:
            np.linalg.cholesky(Aj)
            return np.linalg.inv(Aj)
        except np.linalg.LinAlgError:
            pass

    return np.linalg.pinv(A)

def solve_ridge_lstsq(A, y, ridge=1e-10):
    """
    Solve min ||y - A theta||^2 with tiny ridge stabilization.

    A: [n, q]
    y: [n]
    """
    A = np.asarray(A, dtype=np.float64)
    y = np.asarray(y, dtype=np.float64)

    q = A.shape[1]
    if q == 0:
        return np.zeros(0, dtype=np.float64)

    AtA = A.T @ A
    Aty = A.T @ y

    return np.linalg.solve(
        AtA + ridge * np.eye(q),
        Aty
    )

def make_spd_by_jitter(A, jitter=1e-8, max_tries=12):
    """
    Return A + eps I that is numerically SPD.
    """
    A = np.asarray(A, dtype=np.float64)
    d = A.shape[0]

    A = 0.5 * (A + A.T)

    for k in range(max_tries):
        eps = jitter * (10 ** k)
        Aj = A + eps * np.eye(d)
        try:
            np.linalg.cholesky(Aj)
            return Aj
        except np.linalg.LinAlgError:
            pass

    eigvals = np.linalg.eigvalsh(A)
    min_eig = eigvals.min()
    shift = max(jitter, -min_eig + jitter)
    return A + shift * np.eye(d)

# ============================================================
# 2. RICF 初始化
# ============================================================

def initialize_bap_parameters_ricf(X, graph, ridge=1e-10, min_var=1e-8):
    """
    Initialize B and Omega for a fixed BAP graph.

    Convention:
      graph.D[i,j] = 1 means i -> j
      graph.C[i,j] = 1 means i <-> j

    Model convention:
      E = X (I - B)
      e_j = x_j - sum_i x_i B[i,j]
    """
    X = center_data_np(X)
    n, d = X.shape

    D = np.asarray(graph.D).astype(int)
    C = np.asarray(graph.C).astype(int)

    B = np.zeros((d, d), dtype=np.float64)

    # Initial B by OLS node-wise on directed parents.
    for j in range(d):
        pa = np.where(D[:, j] == 1)[0]

        if len(pa) > 0:
            A = X[:, pa]
            y = X[:, j]
            beta = solve_ridge_lstsq(A, y, ridge=ridge)
            B[pa, j] = beta

    # Residuals under initial B.
    I = np.eye(d)
    E = X @ (I - B)

    # Safe initial Omega:
    # Use diagonal residual variances only.
    Omega = np.zeros((d, d), dtype=np.float64)

    for j in range(d):
        var_j = float(np.mean(E[:, j] ** 2))
        Omega[j, j] = max(var_j, min_var)

    # Optional mild initialization for bidirected entries.
    # This can help, but may break SPD if too large.
    # We therefore shrink if necessary.
    Omega_candidate = Omega.copy()
    for i in range(d):
        for j in range(i):
            if C[i, j] == 1:
                cov_ij = float(np.mean(E[:, i] * E[:, j]))
                Omega_candidate[i, j] = cov_ij
                Omega_candidate[j, i] = cov_ij

    Omega_candidate = 0.5 * (Omega_candidate + Omega_candidate.T)

    try:
        np.linalg.cholesky(Omega_candidate)
        Omega = Omega_candidate
    except np.linalg.LinAlgError:
        # fall back to diagonal Omega
        pass

    Omega = make_spd_by_jitter(Omega, jitter=min_var)

    return B, Omega

# ============================================================
# 3. 固定图 RICF 拟合
# ============================================================

def fit_bap_ricf(
    X,
    graph,
    *,
    max_iter=100,
    tol=1e-6,
    ridge=1e-10,
    min_var=1e-8,
    jitter=1e-10,
    verbose=False,
):
    """
    RICF fitting for a fixed BAP graph.

    This is a residual iterative conditional fitting style implementation.

    Fixed graph constraints:
      - B[i,j] free only if i -> j exists.
      - Omega[i,j] free only if i <-> j exists or i == j.

    Returns:
      {
        "B": B_hat,
        "Omega": Omega_hat,
        "converged": bool,
        "n_iter": int,
        "max_change": float
      }
    """
    graph.validate()

    X = center_data_np(X)
    n, d = X.shape

    D = np.asarray(graph.D).astype(int)
    C = np.asarray(graph.C).astype(int)

    B, Omega = initialize_bap_parameters_ricf(
        X,
        graph,
        ridge=ridge,
        min_var=min_var,
    )

    I = np.eye(d)

    converged = False
    last_max_change = np.inf

    for it in range(max_iter):
        B_old = B.copy()
        Omega_old = Omega.copy()

        for v in range(d):
            pa = np.where(D[:, v] == 1)[0]
            sp = np.where(C[:, v] == 1)[0]

            minus_v = np.array([k for k in range(d) if k != v], dtype=int)

            # Recompute residuals using latest B.
            E = X @ (I - B)

            Omega_minus = Omega[np.ix_(minus_v, minus_v)]
            Omega_minus_inv = safe_inverse_spd(
                Omega_minus,
                jitter=jitter,
            )

            y = X[:, v]

            design_parts = []

            # Directed parent design: X_pa
            if len(pa) > 0:
                X_pa = X[:, pa]
                design_parts.append(X_pa)

            # Spouse pseudo-variable design.
            # Conditional mean part:
            #   E[e_v | e_-v]
            # = Omega[v,-v] Omega[-v,-v]^{-1} e_-v
            #
            # Since Omega[v,-v] is only nonzero on spouses,
            # define Z_sp = E_-v @ Omega[-v,-v]^{-1}[:, spouse_positions]
            # and regress coefficient is Omega[sp, v].
            if len(sp) > 0:
                sp_pos = np.array(
                    [np.where(minus_v == s)[0][0] for s in sp],
                    dtype=int
                )

                E_minus = E[:, minus_v]
                Z_sp = E_minus @ Omega_minus_inv[:, sp_pos]
                design_parts.append(Z_sp)
            else:
                sp_pos = np.array([], dtype=int)

            if len(design_parts) > 0:
                A = np.column_stack(design_parts)
                theta = solve_ridge_lstsq(A, y, ridge=ridge)
                residual = y - A @ theta
            else:
                theta = np.zeros(0, dtype=np.float64)
                residual = y.copy()

            # Parse regression coefficients.
            offset = 0

            beta_pa = np.zeros(len(pa), dtype=np.float64)
            if len(pa) > 0:
                beta_pa = theta[offset:offset + len(pa)]
                offset += len(pa)

            omega_sp = np.zeros(len(sp), dtype=np.float64)
            if len(sp) > 0:
                omega_sp = theta[offset:offset + len(sp)]
                offset += len(sp)

            # Update B column v.
            B[:, v] = 0.0
            if len(pa) > 0:
                B[pa, v] = beta_pa

            # Update Omega row/column v.
            # Preserve Omega[-v,-v], update conditional covariance block.
            Omega[v, :] = 0.0
            Omega[:, v] = 0.0

            if len(sp) > 0:
                Omega[v, sp] = omega_sp
                Omega[sp, v] = omega_sp

            delta_v = float(np.mean(residual ** 2))
            delta_v = max(delta_v, min_var)

            if len(sp) > 0:
                K_ss = Omega_minus_inv[np.ix_(sp_pos, sp_pos)]
                omega_quad = float(omega_sp.T @ K_ss @ omega_sp)
            else:
                omega_quad = 0.0

            Omega[v, v] = delta_v + omega_quad

            # Numerical symmetrization.
            Omega = 0.5 * (Omega + Omega.T)

            # The RICF update should preserve SPD if Omega[-v,-v] is SPD
            # and delta_v > 0. Add tiny jitter for numerical safety.
            Omega = make_spd_by_jitter(Omega, jitter=min_var)

        max_change_B = float(np.max(np.abs(B - B_old)))
        max_change_Om = float(np.max(np.abs(Omega - Omega_old)))
        last_max_change = max(max_change_B, max_change_Om)

        if verbose:
            print(
                f"[RICF] iter={it + 1:03d}, "
                f"max_change={last_max_change:.3e}, "
                f"change_B={max_change_B:.3e}, "
                f"change_Omega={max_change_Om:.3e}"
            )

        if last_max_change < tol:
            converged = True
            break

    # Final cleanup according to graph constraints.
    B = B * D

    Omega_clean = np.zeros_like(Omega)
    np.fill_diagonal(Omega_clean, np.diag(Omega))
    for i in range(d):
        for j in range(i):
            if C[i, j] == 1:
                Omega_clean[i, j] = Omega[i, j]
                Omega_clean[j, i] = Omega[j, i]

    Omega_clean = make_spd_by_jitter(Omega_clean, jitter=min_var)

    return {
        "B": B,
        "Omega": Omega_clean,
        "converged": converged,
        "n_iter": it + 1,
        "max_change": last_max_change,
    }

# ============================================================
# 4. Gaussian log-likelihood
# ============================================================

def gaussian_sem_loglik_from_B_Omega(
    X,
    B,
    Omega,
    *,
    center=True,
    jitter=1e-10,
):
    """
    Gaussian SEM log-likelihood using the residual form.

    Convention:
      B[i,j] means i -> j.
      E = X (I - B).
      E ~ N(0, Omega).

    Therefore:
      log L =
        n log |det(I-B)|
        - n/2 log |Omega|
        - 1/2 tr(E Omega^{-1} E^T)
        - nd/2 log(2pi)
    """
    X = np.asarray(X, dtype=np.float64)
    if center:
        X = center_data_np(X)

    B = np.asarray(B, dtype=np.float64)
    Omega = np.asarray(Omega, dtype=np.float64)

    n, d = X.shape
    I = np.eye(d)

    ImB = I - B

    sign_imb, logdet_imb = np.linalg.slogdet(ImB)
    if sign_imb <= 0 or not np.isfinite(logdet_imb):
        return -np.inf

    sign_om, logdet_om, Omega_used = safe_slogdet(
        Omega,
        jitter=jitter,
    )
    if sign_om <= 0 or not np.isfinite(logdet_om):
        return -np.inf

    E = X @ ImB

    Omega_inv = safe_inverse_spd(
        Omega_used,
        jitter=jitter,
    )

    quad = float(np.einsum("ni,ij,nj->", E, Omega_inv, E))

    ll = (
        n * logdet_imb
        - 0.5 * n * logdet_om
        - 0.5 * quad
        - 0.5 * n * d * math.log(2.0 * math.pi)
    )

    if not np.isfinite(ll):
        return -np.inf

    return float(ll)

def implied_covariance_from_B_Omega(B, Omega):
    """
    For row-vector convention E = X(I-B):
      Cov(X) = (I-B)^(-T) Omega (I-B)^(-1)
    """
    B = np.asarray(B, dtype=np.float64)
    Omega = np.asarray(Omega, dtype=np.float64)

    d = B.shape[0]
    I = np.eye(d)
    ImB_inv = np.linalg.inv(I - B)

    Sigma = ImB_inv.T @ Omega @ ImB_inv
    Sigma = 0.5 * (Sigma + Sigma.T)

    return Sigma

# ============================================================
# 5. RICF-BIC score for fixed graph
# ============================================================

def score_bap_ricf(
    X,
    graph,
    *,
    ricf_max_iter=100,
    ricf_tol=1e-6,
    ridge=1e-10,
    min_var=1e-8,
    jitter=1e-10,
    penalty_coef=1.0,
    include_node_penalty=True,
    verbose=False,
):
    """
    Fit fixed BAP graph by RICF, then compute Nowzohour-style score:

      s(G) = 1/n * ( max_lik - penalty_coef * (d + #edges) log n )

    If include_node_penalty=False:
      s(G) = 1/n * ( max_lik - penalty_coef * #edges log n )

    The original paper includes d + #edges.
    """
    graph.validate()

    X = np.asarray(X, dtype=np.float64)
    X = center_data_np(X)
    n, d = X.shape

    fit = fit_bap_ricf(
        X,
        graph,
        max_iter=ricf_max_iter,
        tol=ricf_tol,
        ridge=ridge,
        min_var=min_var,
        jitter=jitter,
        verbose=verbose,
    )

    B_hat = fit["B"]
    Omega_hat = fit["Omega"]

    ll = gaussian_sem_loglik_from_B_Omega(
        X,
        B_hat,
        Omega_hat,
        center=False,
        jitter=jitter,
    )

    num_edges = graph.num_edges()

    if include_node_penalty:
        num_params_penalty = d + num_edges
    else:
        num_params_penalty = num_edges

    score = (ll - penalty_coef * num_params_penalty * math.log(n)) / n

    Sigma_hat = implied_covariance_from_B_Omega(B_hat, Omega_hat)

    return {
        "graph": graph,
        "score": float(score),
        "loglik": float(ll),
        "B": B_hat,
        "Omega": Omega_hat,
        "Sigma": Sigma_hat,
        "num_edges": int(num_edges),
        "num_params_penalty": int(num_params_penalty),
        "ricf_converged": bool(fit["converged"]),
        "ricf_n_iter": int(fit["n_iter"]),
        "ricf_max_change": float(fit["max_change"]),
    }

# ============================================================
# 6. RICF score greedy hill climbing
# ============================================================

def greedy_hill_climb_bap_ricf(
    X,
    init_graph,
    *,
    ricf_max_iter=100,
    ricf_tol=1e-6,
    ridge=1e-10,
    min_var=1e-8,
    jitter=1e-10,
    penalty_coef=1.0,
    include_node_penalty=True,
    improvement_tol=1e-8,
    max_hill_steps=None,
    verbose=True,
):
    """
    Greedy hill climbing over BAP local neighborhood using RICF-BIC score.
    """
    init_graph.validate()

    X = np.asarray(X, dtype=np.float64)
    X = center_data_np(X)

    current = init_graph.copy()

    current_fit = score_bap_ricf(
        X,
        current,
        ricf_max_iter=ricf_max_iter,
        ricf_tol=ricf_tol,
        ridge=ridge,
        min_var=min_var,
        jitter=jitter,
        penalty_coef=penalty_coef,
        include_node_penalty=include_node_penalty,
        verbose=False,
    )

    current_score = current_fit["score"]

    if verbose:
        print(
            f"[RICF-hill] start score={current_score:.6f}, "
            f"edges={current.num_edges()}, "
            f"ll={current_fit['loglik']:.3f}"
        )

    history = [{
        "graph": current.copy(),
        "score": current_score,
        "fit": current_fit,
    }]

    step = 0

    while True:
        if max_hill_steps is not None and step >= max_hill_steps:
            if verbose:
                print(f"[RICF-hill] reached max_hill_steps={max_hill_steps}")
            break

        neighbors = all_local_neighbors(current)

        if verbose:
            print(
                f"[RICF-hill] step={step}, "
                f"current_score={current_score:.6f}, "
                f"num_neighbors={len(neighbors)}"
            )

        best_neighbor = None
        best_neighbor_fit = None
        best_neighbor_score = current_score

        for k, H in enumerate(neighbors):
            fit_H = score_bap_ricf(
                X,
                H,
                ricf_max_iter=ricf_max_iter,
                ricf_tol=ricf_tol,
                ridge=ridge,
                min_var=min_var,
                jitter=jitter,
                penalty_coef=penalty_coef,
                include_node_penalty=include_node_penalty,
                verbose=False,
            )

            score_H = fit_H["score"]

            if score_H > best_neighbor_score + improvement_tol:
                best_neighbor = H
                best_neighbor_fit = fit_H
                best_neighbor_score = score_H

        if best_neighbor is None:
            if verbose:
                print(
                    f"[RICF-hill] stop at local optimum, "
                    f"score={current_score:.6f}, edges={current.num_edges()}"
                )
            break

        current = best_neighbor
        current_score = best_neighbor_score

        history.append({
            "graph": current.copy(),
            "score": current_score,
            "fit": best_neighbor_fit,
        })

        if verbose:
            print(
                f"[RICF-hill] move: "
                f"score={current_score:.6f}, "
                f"edges={current.num_edges()}, "
                f"ll={best_neighbor_fit['loglik']:.3f}, "
                f"ricf_iter={best_neighbor_fit['ricf_n_iter']}, "
                f"converged={best_neighbor_fit['ricf_converged']}"
            )

        step += 1

    best_fit = history[-1]["fit"]

    return {
        "best_graph": current,
        "best_score": current_score,
        "best_fit": best_fit,
        "history": history,
    }

# ============================================================
# 7. RICF score random restarts
# ============================================================

def bap_greedy_search_ricf(
    X,
    *,
    n_restarts=20,
    include_empty_start=True,
    restart_burnin=500,
    seed=None,
    ricf_max_iter=100,
    ricf_tol=1e-6,
    ridge=1e-10,
    min_var=1e-8,
    jitter=1e-10,
    penalty_coef=1.0,
    include_node_penalty=True,
    improvement_tol=1e-8,
    max_hill_steps=None,
    verbose=True,
):
    """
    Full BAP greedy score-based search using RICF score.

    This is the Nowzohour-style discrete search:
      - random restarts
      - greedy hill climbing
      - fixed-graph RICF MLE
      - BIC-like score

    No tanh penalty.
    No augmented Lagrangian.
    """
    X = np.asarray(X, dtype=np.float64)
    X = center_data_np(X)
    n, d = X.shape

    if seed is not None:
        np.random.seed(seed)
        random.seed(seed)

    restart_graphs = []

    if include_empty_start:
        restart_graphs.append(empty_bap(d))

    for r in range(n_restarts):
        g0 = random_bap_mcmc(
            d=d,
            burnin=restart_burnin,
            seed=None if seed is None else seed + 10000 + r,
            start_graph=None,
        )
        restart_graphs.append(g0)

    all_runs = []

    global_best_score = -np.inf
    global_best_graph = None
    global_best_run = None

    for r, g0 in enumerate(restart_graphs):
        if verbose:
            print("=" * 90)
            print(
                f"[RICF-restart {r + 1}/{len(restart_graphs)}] "
                f"initial edges={g0.num_edges()}"
            )

        run = greedy_hill_climb_bap_ricf(
            X,
            g0,
            ricf_max_iter=ricf_max_iter,
            ricf_tol=ricf_tol,
            ridge=ridge,
            min_var=min_var,
            jitter=jitter,
            penalty_coef=penalty_coef,
            include_node_penalty=include_node_penalty,
            improvement_tol=improvement_tol,
            max_hill_steps=max_hill_steps,
            verbose=verbose,
        )

        all_runs.append(run)

        if run["best_score"] > global_best_score:
            global_best_score = run["best_score"]
            global_best_graph = run["best_graph"].copy()
            global_best_run = run

        if verbose:
            print(
                f"[RICF-restart {r + 1}] local best score={run['best_score']:.6f}, "
                f"edges={run['best_graph'].num_edges()}"
            )

    return {
        "best_graph": global_best_graph,
        "best_score": float(global_best_score),
        "best_run": global_best_run,
        "best_fit": global_best_run["best_fit"] if global_best_run is not None else None,
        "all_runs": all_runs,
    }

