@dataclass
class BAPGraph:
    """
    D[i,j] = 1 means i -> j
    C[i,j] = C[j,i] = 1 means i <-> j
    Diagonal of D and C must be zero.
    """
    D: np.ndarray  # shape [d,d], dtype bool/int
    C: np.ndarray  # shape [d,d], symmetric, zero diagonal

    def copy(self):
        return BAPGraph(self.D.copy(), self.C.copy())

    @property
    def d(self):
        return self.D.shape[0]

    def num_directed_edges(self):
        return int(self.D.sum())

    def num_bidirected_edges(self):
        return int(np.triu(self.C, k=1).sum())

    def num_edges(self):
        return self.num_directed_edges() + self.num_bidirected_edges()

    def validate(self):
        d = self.d
        assert self.D.shape == (d, d)
        assert self.C.shape == (d, d)
        assert np.all(np.diag(self.D) == 0), "D diagonal must be zero"
        assert np.all(np.diag(self.C) == 0), "C diagonal must be zero"
        assert np.all(self.C == self.C.T), "C must be symmetric"
        # bow-free
        assert np.all((self.D + self.D.T + self.C) <= 1), "bow-free violated"
        # acyclic directed part
        assert is_acyclic(self.D), "Directed part must be acyclic"

    def key(self):
        return (self.D.astype(np.uint8).tobytes(), self.C.astype(np.uint8).tobytes())

def empty_bap(d: int) -> BAPGraph:
    return BAPGraph(
        D=np.zeros((d, d), dtype=np.uint8),
        C=np.zeros((d, d), dtype=np.uint8),
    )

