def simulate_linear_gaussian_bap_data(B_true, Omega_true, n, seed=None, dtype=torch.float64):
    """
    根据线性高斯 BAP/ADMG SEM 生成数据。

    约定：
      B_true[i,j] 表示 i -> j 的系数
      X = E (I - B)^(-1),   E ~ N(0, Omega_true)

    因此协方差为
      Cov(X) = (I - B)^(-T) Omega_true (I - B)^(-1)

    注意：
    这和前面搜索代码里的 log_likelihood 保持一致，因为那里用了
      R = X (I - B)
      即 E = X (I - B)
    """
    if seed is not None:
        np.random.seed(seed)
        random.seed(seed)
        torch.manual_seed(seed)

    B_true = np.asarray(B_true, dtype=np.float64)
    Omega_true = np.asarray(Omega_true, dtype=np.float64)

    d = B_true.shape[0]
    I = np.eye(d, dtype=np.float64)

    ImB = I - B_true
    ImB_inv = np.linalg.inv(ImB)

    # Cov(X) = (I-B)^(-T) Omega (I-B)^(-1)
    Sigma_x = ImB_inv.T @ Omega_true @ ImB_inv

    X = np.random.multivariate_normal(
        mean=np.zeros(d, dtype=np.float64),
        cov=Sigma_x,
        size=n
    )

    return torch.tensor(X, dtype=dtype), Sigma_x

