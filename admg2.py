def simulate_linear_scm_i_to_j(n, B, Omega, seed=42):
    """
    X = E (I - B)^(-1), where B[i,j] means i -> j.
    """
    rng = np.random.default_rng(seed)
    p = B.shape[0]
    L = np.linalg.cholesky(Omega)
    E = rng.standard_normal((n, p)) @ L.T
    X = E @ np.linalg.inv(np.eye(p) - B)
    return X


