def generate_b_from_edges(p, edges):
    """
    Generates a directed adjacency matrix B from a list of directed edges.

    Args:
        p (int): The number of nodes.
        edges (list of tuples): A list of tuples, where each tuple (i, j)
                                 represents a directed edge from node i to node j (0-indexed).

    Returns:
        np.ndarray: The p x p adjacency matrix B.
    """
    B = np.zeros((p, p), dtype=np.float32)
    for i, j in edges:
        # Ensure nodes are within bounds
        if 0 <= i < p and 0 <= j < p and i != j:
             # Weights in [-2, -0.5] or [0.5, 2]
            if np.random.rand() > 0.5:
                weight = np.random.uniform(0.5, 2.0)
            else:
                weight = np.random.uniform(-2.0, -0.5)
            B[i, j] = weight
        else:
            print(f"Warning: Invalid edge ({i}, {j}) for p={p}. Skipping.")

    # Optional: Add a check here to see if the generated graph is acyclic.
    # For this task, we assume the user provides edges that form a DAG.
    # In a real application, you might want to implement a check and potentially raise an error.

    return B

def generate_sigma_from_biedges(p, bidirected_edges, weight_range_diag=(0.7, 1.2), weight_range_offdiag=(-0.7, -0.4, 0.4, 0.7)):
    """
    Generates a symmetric Sigma_e matrix from a list of bidirected edges and diagonal elements.

    Args:
        p (int): The number of nodes.
        bidirected_edges (list of tuples): A list of tuples, where each tuple (i, j)
                                          represents a bidirected edge between node i and node j (0-indexed).
                                          Order doesn't matter, (i, j) is same as (j, i).
        weight_range_diag (tuple): Range for diagonal elements (variances).
        weight_range_offdiag (tuple): Ranges for off-diagonal elements (covariances).

    Returns:
        np.ndarray: The p x p symmetric matrix Sigma_e.
    """
    Sigma_e = np.zeros((p, p), dtype=np.float32)

    # Generate diagonal elements (variances)
    diag_values = np.random.uniform(weight_range_diag[0], weight_range_diag[1], p)
    np.fill_diagonal(Sigma_e, diag_values)

    # Generate off-diagonal elements (covariances) based on bidirected edges
    for i, j in bidirected_edges:
        # Ensure nodes are within bounds and not the same node
        if 0 <= i < p and 0 <= j < p and i != j:
            # Only add the edge once (either (i, j) or (j, i))
            # Decide weight
            if np.random.rand() > 0.5:
                weight = np.random.uniform(weight_range_offdiag[2], weight_range_offdiag[3])
            else:
                weight = np.random.uniform(weight_range_offdiag[0], weight_range_offdiag[1])

            Sigma_e[i, j] = weight
            Sigma_e[j, i] = weight # Ensure symmetry
        else:
            print(f"Warning: Invalid bidirected edge ({i}, {j}) for p={p}. Skipping.")

    return Sigma_e



