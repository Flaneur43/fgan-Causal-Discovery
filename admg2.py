def graph_to_SC(graph, d):
    """
    将 SimpleADMG 对象的 di_edges 和 bi_edges 集合转换为 np 矩阵。
    S[i, j] = 1 表示 i -> j
    C[i, j] = 1 表示 i <-> j
    """
    S = np.zeros((d, d), dtype=int)
    C = np.zeros((d, d), dtype=int)

    # 需要将字符串索引转换为整数索引
    for u, v in graph.di_edges:
        S[int(u), int(v)] = 1

    for u, v in graph.bi_edges:
        C[int(u), int(v)] = 1
        C[int(v), int(u)] = 1

    return S, C

